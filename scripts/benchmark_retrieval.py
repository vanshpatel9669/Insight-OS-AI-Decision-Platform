#!/usr/bin/env python3
"""Measures real retrieval latency (p50/p95/p99, per stage) and a
reproducible self-retrieval quality proxy over the built index.

Quality proxy, defined explicitly rather than left implicit: for each
sampled case, its own summary text is used as the search query, and we
check whether the top reranked result shares that case's issue_type. This
is "top-1 issue-type match rate" — a specific, reproducible definition, not
a number chosen to match any external claim. It is NOT the same
measurement as "false positive reduction" in other materials, and no
attempt is made here to reproduce that figure — see README.md.

Usage: python scripts/benchmark_retrieval.py --sample-size 200
"""

from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import random  # noqa: E402

from pymongo import MongoClient  # noqa: E402

from insight_os.config import get_settings  # noqa: E402
from insight_os.db.mongo import CASES_COLLECTION  # noqa: E402
from insight_os.logging_config import configure_logging, get_logger  # noqa: E402
from insight_os.retrieval.embeddings import get_embed_model  # noqa: E402
from insight_os.retrieval.index_store import get_database_cases, load_index  # noqa: E402
from insight_os.retrieval.reranker import get_reranker  # noqa: E402
from insight_os.retrieval.search_service import SearchService  # noqa: E402

INDEX_PERSIST_DIR = Path(__file__).resolve().parent.parent / "storage"
RESULTS_DIR = Path(__file__).resolve().parent.parent / "eval" / "results"


def percentile(values: list[float], pct: float) -> float:
    if not values:
        return 0.0
    values_sorted = sorted(values)
    idx = min(int(len(values_sorted) * pct), len(values_sorted) - 1)
    return values_sorted[idx]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sample-size", type=int, default=200)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    configure_logging()
    logger = get_logger(__name__)
    settings = get_settings()

    client = MongoClient(settings.mongo_uri)
    db = client[settings.mongo_db]
    total_cases = db[CASES_COLLECTION].count_documents({})
    logger.info("benchmark_started", total_cases=total_cases, sample_size=args.sample_size)

    embed_model = get_embed_model(settings.embed_model_name)
    index = load_index(settings.mongo_uri, settings.mongo_db, INDEX_PERSIST_DIR, embed_model)
    reranker = get_reranker(settings.rerank_model_name)
    cases = get_database_cases(db)
    cases_by_id = {c.case_id: c for c in cases}
    service = SearchService(index=index, reranker=reranker, cases_by_id=cases_by_id)

    rng = random.Random(args.seed)
    sample = rng.sample(cases, min(args.sample_size, len(cases)))

    vector_ms, rerank_ms, total_ms = [], [], []
    top1_issue_type_matches = 0

    for case in sample:
        result = service.search(case.summary, retrieval_top_k=20, final_top_k=5)
        vector_ms.append(result.timing_ms["vector_retrieve_ms"])
        rerank_ms.append(result.timing_ms["rerank_ms"])
        total_ms.append(result.timing_ms["total_ms"])
        if result.results and result.results[0].case.issue_type == case.issue_type:
            top1_issue_type_matches += 1

    match_rate = top1_issue_type_matches / len(sample) if sample else 0.0

    report_lines = [
        "# Retrieval Benchmark Report",
        "",
        "**Machine-generated by `scripts/benchmark_retrieval.py`. Every number "
        "below comes from this run against the real built index — nothing here "
        "is a target or a claim copied from elsewhere.**",
        "",
        f"- Corpus size: {total_cases} synthetic cases (see "
        "`scripts/generate_synthetic_cases.py` — not the 1M+ figure in other "
        "materials; see README.md).",
        f"- Query sample size: {len(sample)} (case summaries used as queries).",
        "- Retrieval candidates before reranking: 20. Final results after reranking: 5.",
        "",
        "## Latency (ms, self-reported per-request by the search service)",
        "",
        "| Stage | p50 | p95 | p99 |",
        "|---|---|---|---|",
        f"| Vector retrieve | {percentile(vector_ms, 0.5):.1f} | "
        f"{percentile(vector_ms, 0.95):.1f} | {percentile(vector_ms, 0.99):.1f} |",
        f"| Rerank | {percentile(rerank_ms, 0.5):.1f} | "
        f"{percentile(rerank_ms, 0.95):.1f} | {percentile(rerank_ms, 0.99):.1f} |",
        f"| Total | {percentile(total_ms, 0.5):.1f} | "
        f"{percentile(total_ms, 0.95):.1f} | {percentile(total_ms, 0.99):.1f} |",
        "",
        f"## Retrieval quality: top-1 issue-type match rate: {match_rate:.1%}",
        "",
        "Defined as: using a case's own summary as the query, does the "
        "highest-reranked result share that case's `issue_type`? This is a "
        "self-retrieval proxy for relevance, not a labeled human-judged "
        "benchmark, and it is NOT the same measurement as any external "
        "false-positive-reduction figure — no attempt was made to reproduce "
        "that number.",
        "",
        f"Mean/stdev total latency: {statistics.mean(total_ms):.1f}ms / "
        f"{statistics.pstdev(total_ms):.1f}ms.",
    ]
    report = "\n".join(report_lines) + "\n"

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "retrieval_benchmark.md").write_text(report)
    print(report)
    print(f"Wrote {RESULTS_DIR / 'retrieval_benchmark.md'}")


if __name__ == "__main__":
    main()
